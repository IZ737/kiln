use kiln_diagnostics::Span;
use std::fmt;

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

/// One piece of a string literal: literal text, or the tokens of an
/// interpolated `${...}` expression.
#[derive(Clone, Debug, PartialEq)]
pub enum StrPart {
    Text(String),
    Interp(Vec<Token>, Span),
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Ident(String),
    Int(String),
    Float(String),
    /// A number with a time unit, such as `2s` or `250ms`.
    Duration(String),
    Str(Vec<StrPart>),
    Newline,
    Eof,

    // Keywords
    And,
    Break,
    Catch,
    Const,
    Continue,
    Else,
    Enum,
    False,
    Fn,
    For,
    If,
    Impl,
    Import,
    In,
    Is,
    Let,
    Match,
    None,
    Not,
    Or,
    Pub,
    Return,
    Struct,
    Throw,
    True,
    Try,
    Var,
    Where,
    While,

    // Punctuation
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Dot,
    DotDot,
    Colon,
    Semi,
    Arrow,
    FatArrow,
    Eq,
    EqEq,
    NotEq,
    Lt,
    Le,
    Gt,
    Ge,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Bang,
    Question,
    QuestionQuestion,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    // Symbols from other languages, lexed so the parser can suggest a fix.
    EqEqEq,
    BangEqEq,
    AmpAmp,
    PipePipe,
}

impl TokenKind {
    pub fn keyword(word: &str) -> Option<TokenKind> {
        use TokenKind::*;
        Some(match word {
            "and" => And,
            "break" => Break,
            "catch" => Catch,
            "const" => Const,
            "continue" => Continue,
            "else" => Else,
            "enum" => Enum,
            "false" => False,
            "fn" => Fn,
            "for" => For,
            "if" => If,
            "impl" => Impl,
            "import" => Import,
            "in" => In,
            "is" => Is,
            "let" => Let,
            "match" => Match,
            "none" => None,
            "not" => Not,
            "or" => Or,
            "pub" => Pub,
            "return" => Return,
            "struct" => Struct,
            "throw" => Throw,
            "true" => True,
            "try" => Try,
            "var" => Var,
            "where" => Where,
            "while" => While,
            _ => return Option::None,
        })
    }
}

impl fmt::Display for TokenKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        use TokenKind::*;
        let s = match self {
            Ident(name) => return write!(f, "`{name}`"),
            Int(_) | Float(_) => "a number",
            Duration(_) => "a duration",
            Str(_) => "a string",
            Newline => "end of line",
            Eof => "end of file",
            And => "`and`",
            Break => "`break`",
            Catch => "`catch`",
            Const => "`const`",
            Continue => "`continue`",
            Else => "`else`",
            Enum => "`enum`",
            False => "`false`",
            Fn => "`fn`",
            For => "`for`",
            If => "`if`",
            Impl => "`impl`",
            Import => "`import`",
            In => "`in`",
            Is => "`is`",
            Let => "`let`",
            Match => "`match`",
            None => "`none`",
            Not => "`not`",
            Or => "`or`",
            Pub => "`pub`",
            Return => "`return`",
            Struct => "`struct`",
            Throw => "`throw`",
            True => "`true`",
            Try => "`try`",
            Var => "`var`",
            Where => "`where`",
            While => "`while`",
            LParen => "`(`",
            RParen => "`)`",
            LBrace => "`{`",
            RBrace => "`}`",
            LBracket => "`[`",
            RBracket => "`]`",
            Comma => "`,`",
            Dot => "`.`",
            DotDot => "`..`",
            Colon => "`:`",
            Semi => "`;`",
            Arrow => "`->`",
            FatArrow => "`=>`",
            Eq => "`=`",
            EqEq => "`==`",
            NotEq => "`!=`",
            Lt => "`<`",
            Le => "`<=`",
            Gt => "`>`",
            Ge => "`>=`",
            Plus => "`+`",
            Minus => "`-`",
            Star => "`*`",
            Slash => "`/`",
            Percent => "`%`",
            Bang => "`!`",
            Question => "`?`",
            QuestionQuestion => "`??`",
            PlusEq => "`+=`",
            MinusEq => "`-=`",
            StarEq => "`*=`",
            SlashEq => "`/=`",
            EqEqEq => "`===`",
            BangEqEq => "`!==`",
            AmpAmp => "`&&`",
            PipePipe => "`||`",
        };
        f.write_str(s)
    }
}
